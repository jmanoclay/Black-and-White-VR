"""Generate src/game/bw_symbols.h from tools/symbols/wanted.txt and the bw1-decomp symbol map.

Usage: python tools/symbols/gen_symbols.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SYMBOLS = ROOT / "third_party" / "bw1-decomp" / "symbols_BW1W120.txt"
WANTED = ROOT / "tools" / "symbols" / "wanted.txt"
OUT = ROOT / "src" / "game" / "bw_symbols.h"

LINE = re.compile(r"^(\S+) = \.(\w+):0x([0-9A-Fa-f]+);(?: // (.*))?")


def load_symbols(path):
    table = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = LINE.match(line)
        if m:
            table[m.group(1)] = (m.group(2), int(m.group(3), 16), m.group(4) or "")
    return table


def main():
    table = load_symbols(SYMBOLS)
    rows, missing = [], []
    for raw in WANTED.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        alias, mangled = line.split(None, 1)
        if mangled not in table:
            missing.append(mangled)
            continue
        section, addr, info = table[mangled]
        rows.append((alias, addr, section, mangled))
    if missing:
        sys.exit("missing symbols:\n  " + "\n  ".join(missing))

    out = [
        "// Generated by tools/symbols/gen_symbols.py from bw1-decomp BW1W120 symbols. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace bw::sym {",
        "",
    ]
    width = max(len(r[0]) for r in rows)
    for alias, addr, section, mangled in rows:
        out.append(f"constexpr uintptr_t {alias:<{width}} = 0x{addr:08X}; // .{section} {mangled}")
    out += ["", "}  // namespace bw::sym", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} symbols)")


if __name__ == "__main__":
    main()
